# Assert-интроспекция — это обычная инструкция Python вида assert <условие>[, <сообщение>],
# которая при падении показывает разбор выражения: левую/правую части, значения подвыражений, красивый дифф коллекций/строк.
#
# Traceback — это отчёт о том, по какой цепочке функций Python дошел до места где произошло исключение.
#
# Фикстуры в pytest — это функции, которые готовят ресурсы для тестов (данные, подключения, конфиги) и отдают его тесту как аргумент по имени и затем корректно убирают.
# Это удобный способ интегрировать в тест необходимые зависимости.
#
# Mark‑функции — это ярлыки для тестов в виде функций‑декораторов.
# Ими помечают функции тестов, чтобы исключать/выбирать при запуске, условно пропускать или ожидать падения, группировать и так далее
#
# Хуки — это специальный‑функции, с помощью которых можно настраивать поведение pytest без изменения самих тестов.
#
# Моки — это подменные объекты, которые имитируют поведение внешних зависимостей в тестах: БД, сеть, время, файл-система и т. п.
# С моками вы проверяете как ваш код взаимодействует с зависимостью (какие функции вызвал, с какими аргументами), не трогая реальный мир.
